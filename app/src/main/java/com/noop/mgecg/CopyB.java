// FILE VERSION 0.77.0 (21 Nov 2026): copy C, the third copy, built with  gradle assembleDebug -PcopyC=1  (applicationId com.noop.mgecg.c, "MG Heart C", versionName ending -C, folder suffix C).
// B is true in copy B AND copy C (both choose their strap at run time and share nothing with copy A); C is true only in copy C; SFX is "" in A, "B" in B, "C" in C.
// FILE VERSION 0.70.0 (17 Nov 2026): the second copy of the app, for a second strap (addendum 197.4, 198.7 and 265).
// Copy B is the same source built with  gradle assembleDebug -PcopyB=1 : applicationId com.noop.mgecg.b (installs BESIDE copy A, same signing key),
// launcher name "MG Heart B", versionName ending -B, and its own folders in Download (the folder names below get the suffix B).
// Copy A (the normal build) has an empty suffix, so every name in copy A is exactly what it was before 0.70.0.
final class CopyB {
    private CopyB() { }

    /** True only in the copy built with -PcopyB=1 (BuildConfig.COPY_B is generated by Gradle from build.gradle). */
    static final boolean B = BuildConfig.COPY_B || BuildConfig.COPY_C;

    /** 0.77.0: True only in the copy built with -PcopyC=1 (BuildConfig.COPY_C). */
    static final boolean C = BuildConfig.COPY_C;

    /** "" in copy A, "B" in copy B, "C" in copy C (0.77.0): appended to every shared Download folder name (MGbackup -> MGbackupB). */
    static final String SFX = C ? "C" : (B ? "B" : "");
}
